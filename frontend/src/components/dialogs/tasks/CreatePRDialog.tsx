import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import { Label } from '@radix-ui/react-label';
import { Textarea } from '@/components/ui/textarea.tsx';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Checkbox } from '@/components/ui/checkbox';
import { Alert, AlertDescription, AlertTitle } from '@/components/ui/alert';
import BranchSelector from '@/components/tasks/BranchSelector';
import { useCallback, useEffect, useMemo, useState } from 'react';
import { useApi } from '@/hooks/useApi';
import { useTranslation } from 'react-i18next';

import { Task, Workspace } from 'shared/types';
import type { ProviderKind } from 'shared/types';
import { Loader2 } from 'lucide-react';
import { useModal } from '@ebay/nice-modal-react';
import { useAuth, useRepoBranches } from '@/hooks';
import {
  GhCliHelpInstructions,
  GhCliSetupDialog,
  mapGhCliErrorToUi,
} from '@/components/dialogs/auth/GhCliSetupDialog';
import type {
  GhCliSupportContent,
  GhCliSupportVariant,
} from '@/components/dialogs/auth/GhCliSetupDialog';
import {
  GlabCliHelpInstructions,
  GlabCliSetupDialog,
  mapGlabCliErrorToUi,
} from '@/components/dialogs/auth/GlabCliSetupDialog';
import type {
  GlabCliSupportContent,
  GlabCliSupportVariant,
} from '@/components/dialogs/auth/GlabCliSetupDialog';
import type { GhCliSetupError } from 'shared/types';
import { useUserSystem } from '@/components/ConfigProvider';
import { defineModal, createModal } from '@/lib/modals';

interface CreatePRDialogProps {
  attempt: Workspace;
  task: Task;
  repoId: string;
  targetBranch?: string;
  provider?: ProviderKind;
}

export type CreatePRDialogResult = {
  success: boolean;
  error?: string;
};

const CreatePRDialogImpl = createModal<CreatePRDialogProps>(
  ({ attempt, task, repoId, targetBranch, provider }) => {
    const { attemptsApi } = useApi();
    const modal = useModal();
    const { t } = useTranslation('tasks');
    const { isLoaded } = useAuth();
    const { environment, config } = useUserSystem();
    const [prTitle, setPrTitle] = useState('');
    const [prBody, setPrBody] = useState('');
    const [prBaseBranch, setPrBaseBranch] = useState('');
    const [creatingPR, setCreatingPR] = useState(false);
    const [error, setError] = useState<string | null>(null);
    const [ghCliHelp, setGhCliHelp] = useState<GhCliSupportContent | null>(
      null
    );
    const [glabCliHelp, setGlabCliHelp] =
      useState<GlabCliSupportContent | null>(null);
    const [isDraft, setIsDraft] = useState(false);
    const [autoGenerateDescription, setAutoGenerateDescription] = useState(
      config?.pr_auto_description_enabled ?? false
    );

    const isGitLab = provider === 'git_lab';

    const titleKey = isGitLab ? 'createMrDialog.title' : 'createPrDialog.title';
    const descriptionKey = isGitLab
      ? 'createMrDialog.description'
      : 'createPrDialog.description';
    const titlePlaceholderKey = isGitLab
      ? 'createMrDialog.titlePlaceholder'
      : 'createPrDialog.titlePlaceholder';
    const descriptionPlaceholderKey = isGitLab
      ? 'createMrDialog.descriptionPlaceholder'
      : 'createPrDialog.descriptionPlaceholder';
    const baseBranchLabelKey = isGitLab
      ? 'createMrDialog.baseBranchLabel'
      : 'createPrDialog.baseBranchLabel';
    const selectBaseBranchKey = isGitLab
      ? 'createMrDialog.selectBaseBranch'
      : 'createPrDialog.selectBaseBranch';
    const autoGenerateLabelKey = isGitLab
      ? 'createMrDialog.autoGenerateLabel'
      : 'createPrDialog.autoGenerateLabel';
    const createButtonKey = isGitLab
      ? 'createMrDialog.createButton'
      : 'createPrDialog.createButton';
    const failedToCreateKey = isGitLab
      ? 'createMrDialog.errors.failedToCreate'
      : 'createPrDialog.errors.failedToCreate';
    const targetBranchNotFoundKey = isGitLab
      ? 'createMrDialog.errors.targetBranchNotFound'
      : 'createPrDialog.errors.targetBranchNotFound';

    const { data: branches = [], isLoading: branchesLoading } = useRepoBranches(
      repoId,
      { enabled: modal.visible && !!repoId }
    );

    const getGhCliHelpTitle = (variant: GhCliSupportVariant) =>
      variant === 'homebrew'
        ? 'Homebrew is required for automatic setup'
        : 'GitHub CLI needs manual setup';

    const getGlabCliHelpTitle = (variant: GlabCliSupportVariant) =>
      variant === 'homebrew'
        ? 'Homebrew is required for automatic setup'
        : 'GitLab CLI needs manual setup';

    // Initialize form when dialog opens
    useEffect(() => {
      if (!modal.visible || !isLoaded) {
        return;
      }

      setPrTitle(task.title);
      setPrBody(task.description || '');
      setError(null);
      setGhCliHelp(null);
      setGlabCliHelp(null);
    }, [modal.visible, isLoaded, task]);

    // Set default base branch when branches are loaded
    useEffect(() => {
      if (branches.length > 0 && !prBaseBranch) {
        // First priority: use the target branch from attempt config
        if (targetBranch && branches.some((b) => b.name === targetBranch)) {
          setPrBaseBranch(targetBranch);
          return;
        }
        // Fallback: use the current branch
        const currentBranch = branches.find((b) => b.is_current);
        if (currentBranch) {
          setPrBaseBranch(currentBranch.name);
        }
      }
    }, [branches, prBaseBranch, targetBranch]);

    const isMacEnvironment = useMemo(
      () => environment?.os_type?.toLowerCase().includes('mac'),
      [environment?.os_type]
    );

    // Linux uses Homebrew on Linux (linuxbrew) — falls back to manual variant
    // via BREW_MISSING error when brew isn't installed.
    const isBrewSupportedEnvironment = useMemo(
      () =>
        environment?.os_family === 'macos' ||
        environment?.os_family === 'linux',
      [environment?.os_family]
    );

    const handleConfirmCreatePR = useCallback(async () => {
      if (!repoId || !attempt.id) return;

      setError(null);
      setGhCliHelp(null);
      setGlabCliHelp(null);
      setCreatingPR(true);

      const handleGhCliSetupOutcome = (
        setupResult: GhCliSetupError | null,
        fallbackMessage: string
      ) => {
        if (setupResult === null) {
          setError(null);
          setGhCliHelp(null);
          setGlabCliHelp(null);
          setCreatingPR(false);
          modal.hide();
          return;
        }

        const ui = mapGhCliErrorToUi(setupResult, fallbackMessage, t);

        if (ui.variant) {
          setGhCliHelp(ui);
          setGlabCliHelp(null);
          setError(null);
          return;
        }

        setGhCliHelp(null);
        setGlabCliHelp(null);
        setError(ui.message);
      };

      const result = await attemptsApi.createPR(attempt.id, {
        title: prTitle,
        body: prBody || null,
        target_branch: prBaseBranch || null,
        draft: isDraft,
        auto_generate_description: autoGenerateDescription,
        repo_id: repoId,
      });

      if (result.success) {
        setPrTitle('');
        setPrBody('');
        setPrBaseBranch('');
        setIsDraft(false);
        setAutoGenerateDescription(
          config?.pr_auto_description_enabled ?? false
        );
        setCreatingPR(false);
        modal.resolve({ success: true } as CreatePRDialogResult);
        modal.hide();
        return;
      }

      setCreatingPR(false);

      const defaultGhCliErrorMessage =
        result.message || 'Failed to run GitHub CLI setup.';

      const defaultGlabCliErrorMessage =
        result.message || 'Failed to run glab CLI setup.';

      const showGhCliSetupDialog = async () => {
        const setupResult = await GhCliSetupDialog.show({
          attemptId: attempt.id,
        });

        handleGhCliSetupOutcome(setupResult, defaultGhCliErrorMessage);
      };

      const showGlabCliSetupDialog = async () => {
        const setupResult = await GlabCliSetupDialog.show({
          attemptId: attempt.id,
        });

        if (setupResult === null) {
          setError(null);
          setGhCliHelp(null);
          setGlabCliHelp(null);
          modal.hide();
          return;
        }

        const ui = mapGlabCliErrorToUi(
          setupResult,
          defaultGlabCliErrorMessage,
          t
        );

        if (ui.variant) {
          setGlabCliHelp(ui);
          setGhCliHelp(null);
          setError(null);
          return;
        }

        setGlabCliHelp(null);
        setGhCliHelp(null);
        setError(ui.message);
      };

      if (result.error) {
        if (
          result.error.type === 'cli_not_installed' ||
          result.error.type === 'cli_not_logged_in'
        ) {
          // Only show setup dialog for GitHub CLI on Mac
          if (result.error.provider === 'git_hub' && isMacEnvironment) {
            await showGhCliSetupDialog();
            return;
          }
          if (
            result.error.provider === 'git_lab' &&
            isBrewSupportedEnvironment
          ) {
            await showGlabCliSetupDialog();
            return;
          }
          const providerName =
            result.error.provider === 'git_hub'
              ? 'GitHub'
              : result.error.provider === 'azure_dev_ops'
                ? 'Azure DevOps'
                : result.error.provider === 'git_lab'
                  ? 'GitLab'
                  : 'Git host';
          const action =
            result.error.type === 'cli_not_installed'
              ? 'not installed'
              : 'not logged in';
          setError(`${providerName} CLI is ${action}`);
          setGhCliHelp(null);
          setGlabCliHelp(null);
          return;
        } else if (
          result.error.type === 'git_cli_not_installed' ||
          result.error.type === 'git_cli_not_logged_in'
        ) {
          const gitCliErrorKey =
            result.error.type === 'git_cli_not_logged_in'
              ? 'createPrDialog.errors.gitCliNotLoggedIn'
              : 'createPrDialog.errors.gitCliNotInstalled';

          setError(result.message || t(gitCliErrorKey));
          setGhCliHelp(null);
          setGlabCliHelp(null);
          return;
        } else if (result.error.type === 'target_branch_not_found') {
          setError(
            t(targetBranchNotFoundKey, {
              branch: result.error.branch,
            })
          );
          setGhCliHelp(null);
          setGlabCliHelp(null);
          return;
        }
      }

      if (result.message) {
        setError(result.message);
        setGhCliHelp(null);
        setGlabCliHelp(null);
      } else {
        setError(t(failedToCreateKey));
        setGhCliHelp(null);
        setGlabCliHelp(null);
      }
    }, [
      attempt,
      repoId,
      prBaseBranch,
      prBody,
      prTitle,
      isDraft,
      autoGenerateDescription,
      config?.pr_auto_description_enabled,
      modal,
      isMacEnvironment,
      isBrewSupportedEnvironment,
      t,
      failedToCreateKey,
      targetBranchNotFoundKey,
    ]);

    const handleCancelCreatePR = useCallback(() => {
      // Return error if one was set, otherwise just canceled
      const result: CreatePRDialogResult = error
        ? { success: false, error }
        : { success: false };
      modal.resolve(result);
      modal.hide();
      // Reset form to empty state
      setPrTitle('');
      setPrBody('');
      setPrBaseBranch('');
      setIsDraft(false);
      setAutoGenerateDescription(config?.pr_auto_description_enabled ?? false);
    }, [modal, config?.pr_auto_description_enabled, error]);

    return (
      <>
        <Dialog
          open={modal.visible}
          onOpenChange={() => handleCancelCreatePR()}
        >
          <DialogContent className="sm:max-w-[525px]">
            <DialogHeader>
              <DialogTitle>{t(titleKey)}</DialogTitle>
              <DialogDescription>{t(descriptionKey)}</DialogDescription>
            </DialogHeader>
            {!isLoaded ? (
              <div className="flex justify-center py-8">
                <Loader2 className="h-6 w-6 animate-spin text-muted-foreground" />
              </div>
            ) : (
              <div className="space-y-4 py-4">
                <div className="flex items-center space-x-2">
                  <Checkbox
                    id="pr-auto-generate"
                    checked={autoGenerateDescription}
                    onCheckedChange={setAutoGenerateDescription}
                    className="h-5 w-5"
                  />
                  <Label
                    htmlFor="pr-auto-generate"
                    className="cursor-pointer text-sm"
                  >
                    {t(autoGenerateLabelKey)}
                  </Label>
                </div>
                <div className="space-y-2">
                  <Label htmlFor="pr-title">
                    {t('createPrDialog.titleLabel')}
                  </Label>
                  <Input
                    id="pr-title"
                    value={prTitle}
                    onChange={(e) => setPrTitle(e.target.value)}
                    placeholder={t(titlePlaceholderKey)}
                  />
                </div>
                <div className="space-y-2">
                  <Label htmlFor="pr-body">
                    {t('createPrDialog.descriptionLabel')}
                  </Label>
                  <Textarea
                    id="pr-body"
                    value={prBody}
                    onChange={(e) => setPrBody(e.target.value)}
                    placeholder={t(descriptionPlaceholderKey)}
                    rows={4}
                    disabled={autoGenerateDescription}
                    className={
                      autoGenerateDescription
                        ? 'opacity-50 cursor-not-allowed'
                        : ''
                    }
                  />
                </div>
                <div className="space-y-2">
                  <Label htmlFor="pr-base">{t(baseBranchLabelKey)}</Label>
                  <BranchSelector
                    branches={branches}
                    selectedBranch={prBaseBranch}
                    onBranchSelect={setPrBaseBranch}
                    placeholder={
                      branchesLoading
                        ? t('createPrDialog.loadingBranches')
                        : t(selectBaseBranchKey)
                    }
                    className={
                      branchesLoading ? 'opacity-50 cursor-not-allowed' : ''
                    }
                  />
                </div>
                <div className="flex items-center space-x-2">
                  <Checkbox
                    id="pr-draft"
                    checked={isDraft}
                    onCheckedChange={setIsDraft}
                    className="h-5 w-5"
                  />
                  <Label htmlFor="pr-draft" className="cursor-pointer text-sm">
                    {t('createPrDialog.draftLabel')}
                  </Label>
                </div>
                {ghCliHelp?.variant && (
                  <Alert variant="default">
                    <AlertTitle>
                      {getGhCliHelpTitle(ghCliHelp.variant)}
                    </AlertTitle>
                    <AlertDescription className="space-y-3">
                      <p>{ghCliHelp.message}</p>
                      <GhCliHelpInstructions
                        variant={ghCliHelp.variant}
                        t={t}
                      />
                    </AlertDescription>
                  </Alert>
                )}
                {glabCliHelp?.variant && (
                  <Alert variant="default">
                    <AlertTitle>
                      {getGlabCliHelpTitle(glabCliHelp.variant)}
                    </AlertTitle>
                    <AlertDescription className="space-y-3">
                      <p>{glabCliHelp.message}</p>
                      <GlabCliHelpInstructions
                        variant={glabCliHelp.variant}
                        t={t}
                      />
                    </AlertDescription>
                  </Alert>
                )}
                {error && <Alert variant="destructive">{error}</Alert>}
              </div>
            )}
            <DialogFooter>
              <Button variant="outline" onClick={handleCancelCreatePR}>
                {t('common:buttons.cancel')}
              </Button>
              <Button
                onClick={handleConfirmCreatePR}
                disabled={creatingPR || !prTitle.trim()}
                className="bg-blue-600 hover:bg-blue-700"
              >
                {creatingPR ? (
                  <>
                    <Loader2 className="mr-2 h-4 w-4 animate-spin" />
                    {t('createPrDialog.creating')}
                  </>
                ) : (
                  t(createButtonKey)
                )}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      </>
    );
  }
);

export const CreatePRDialog = defineModal<
  CreatePRDialogProps,
  CreatePRDialogResult
>(CreatePRDialogImpl);
